                <div class="guide-card">
                    <h3 class="subsection-title">¿Cuándo salen?</h3>
                    <p>Las setas están formadas en su mayor parte por agua, por lo tanto tenemos que buscarlas, sobre
                        todo, cuando tengamos humedad y una temperatura media, ni muy fría ni muy calurosa.</p>
                    <p>Las mejores épocas suelen ser <strong>primavera y otoño</strong> (estaciones húmedas con
                        temperaturas suaves) o los veranos lluviosos. Los diversos géneros tienen sus preferencias:</p>
                    <ul class="simple-list">
                        <li><strong>Primavera:</strong> <em>Entoloma, Morchella</em>, etc.</li>
                        <li><strong>Verano:</strong> <em>Russula, Cantharellus</em> y <em>Boletus</em>.</li>
                        <li><strong>Otoño:</strong> Prácticamente de todo.</li>
                        <li><strong>Invierno:</strong> <em>Tricholoma, Lepista, Hygrophorus</em>, etc.</li>
                    </ul>
                </div>

                <div class="guide-card">
                    <h3 class="subsection-title">¿Dónde salen?</h3>
                    <p>Depende de lo que vayamos buscando tendremos que ir a un hábitat u otro.</p>
                    <p>Si buscamos <em>Agaricus, Marasmius oreades</em> (senderuela) o <em>Calocybe gambosa</em> (zuza,
                        perretxiko) iremos a <strong>praderas</strong>. Si buscamos setas simbiontes iremos a
                        <strong>bosques</strong>.
                    </p>
                    <p>Donde tenemos más probabilidades de encontrar setas es en zonas boscosas: si hace calor, en
                        bosques frescos de frondosas; y si es en tiempo frío, en coníferas, que ofrecen más protección
                        contra las heladas invernales.</p>
                </div>

            </div>

            <div class="rules-box">
                <h2 class="section-title">Normas Cívicas de Recogida</h2>
                <p class="rules-intro">Cuando uno empieza esta bonita afición es conveniente ir bien equipado. Además,
                    hay que tener en cuenta una serie de normas no escritas que todos los que amamos la Naturaleza
                    procuramos seguir e inculcar a los que empiezan:</p>

                <div class="rules-columns">
                    <ul class="rules-list">
                        <li><strong>Lleva cesta de mimbre o castaño:</strong> Permite que las setas vayan aireadas,
                            lleguen en buenas condiciones y sigan soltando esporas por el camino para colonizar nuevas
                            zonas.</li>
                        <li><strong>Usa cachaba o bastón:</strong> Necesaria para mover hojas secas o en zonas de
                            difícil acceso (zarzas), y para evitar sorpresas con víboras u otros animales.</li>
                        <li><strong>Utiliza navaja:</strong> Útil para limpiar la seta en el sitio (así no te llevas
                            tierra a casa) o para cortar por la base aquellas especies en las que arrancar estropearía
                            el micelio.</li>
                        <li><strong>Solo ejemplares sanos:</strong> No cojas setas viejas, secas o agusanadas. Acabarán
                            en la basura y en el monte cumplen la labor inestimable de soltar esporas y alimentar
                            animales.</li>
                    </ul>
                    <ul class="rules-list">
                        <li><strong>Cuidado con las desconocidas:</strong> No cojas setas que no conozcas (o a lo sumo,
                            coge un par de ejemplares enteros para consultar con un experto de la asociación).</li>
                        <li><strong>Respeta el entorno:</strong> Cuida los árboles, frutos, plantas y animales. No mates
                            limacos, víboras ni ningún otro animal; todos tienen su función en el ciclo biológico.</li>
                        <li><strong>Aparca donde debes:</strong> No entres con los coches en zonas no autorizadas. Uno
                            de los mayores placeres de recoger setas es caminar por el bosque.</li>
                        <li><strong>No dejes rastro:</strong> No dejes restos que delaten tu paso (latas, plásticos,
                            paquetes de tabaco, etc.). El monte debe quedar igual que lo encontraste.</li>
                    </ul>
