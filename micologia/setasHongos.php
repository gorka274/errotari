                    Tienen que tomar el alimento ya prefabricado sacándolo de otros organismos (vegetales o animales).
                    Según la forma de obtener este alimento, los hongos se dividen en tres grandes grupos:</p>
            </div>

            <div class="feeding-grid">

                <div class="feeding-card">
                    <div class="card-icon"></div>
                    <h3>Hongos Parásitos</h3>
                    <p>Son los que se alimentan de organismos vivos sin darle nada a cambio, llegando en la mayoría de
                        los casos a provocarles la muerte. La mayoría son oportunistas, invadiendo la planta huésped
                        cuando está debilitada o enferma.</p>
                    <div class="examples">
                        <strong>Ejemplos:</strong>
                        <ul>
                            <li><em>Armillaria mellea</em> (parasita robles, hayas...)</li>
                            <li><em>Xerocomus parasiticus</em> (parasita otros hongos)</li>
                            <li><em>Cordyceps militaris</em> (parasita insectos)</li>
                        </ul>
                    </div>
                </div>

                <div class="feeding-card">
                    <div class="card-icon"></div>
                    <h3>Hongos Saprófitos</h3>
                    <p>Viven sobre materia orgánica muerta. Son abundantes en los bosques y actúan como recicladores de
                        la naturaleza, desintegrando plantas y animales para convertirlos en abono y formar el "humus"
                        de los bosques.</p>
                    <div class="examples">
                        <strong>Ejemplos:</strong>
                        <ul>
                            <li><em>Coprinus comatus</em> (urbeltz, barbuda)</li>
                            <li><em>Clitocybe nebularis</em> (illarraka, pardilla)</li>
                            <li><em>Asterophora lycoperdoides</em></li>
                        </ul>
                    </div>
                </div>

                <div class="feeding-card">
                    <div class="card-icon"></div>
                    <h3>Hongos Simbiontes</h3>
                    <p>Forman una asociación de beneficio mutuo con plantas y árboles (micorriza). El hongo ayuda a la
                        planta a absorber minerales y agua, y la planta le da al hongo los nutrientes que este no puede
                        fabricar. Son vitales para la salud de nuestros bosques.</p>
                    <div class="examples">
                        <strong>Ejemplos:</strong>
                        <ul>
                            <li><em>Boletus edulis</em> (Onddo zuri)</li>
