                        Bizkaia, menos frecuente cuanto más nos desplazamos hacia el sur. A pesar de ser foránea alberga
                        a la mayoría de especies micológicas autóctonas propias de pinares, siendo un ecosistema rico en
                        especies.</p>
                    <p>Los ecosistemas autóctonos predominan en la parte sur, hayedos y robledales sobre todo, pinares
                        silvestres, abedules, píceas, alisos, fresnos, y prados de media montaña. Merecen especial
                        atención los encinares cantábricos que pueblan las faldas de las peñas, y que se encuentran en
                        peligro de desaparición. Estos ecosistemas son los más ricos en flora micológica.</p>
                    <p>Existen plantaciones importantes de otras especies foráneas (alerce japonés, ciprés de Lawson,
                        roble americano...) que también contienen un buen número de especies. No ocurre lo mismo con los
                        Eucaliptos, árboles demasiado exóticos que solo contribuyen a empobrecer los lugares que
                        colonizan; afortunadamente están muy poco extendidos por su aclimatación dificultosa.</p>
