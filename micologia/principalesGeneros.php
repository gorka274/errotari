            <!-- Agaricus -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Agaricus</h2>
                <p>Comprende especies carnosas en su mayoría, todas terrícolas encontrándose generalmente en campas, praderas, pastizales, etc., aunque existan varias especies de bosque. Generalmente son blanquecinas dándole popularmente el nombre de <strong>champiñones</strong>; son heterogéneas, es decir, que se separa fácilmente el pie del sombrero, las esporas al madurar son negruzcas, dándole ese color a las láminas que de jóvenes son rosadas o de color salmón. El sombrero es cerrado de joven, el pie robusto generalmente y está provisto de un <strong>anillo</strong> que puede ser doble y más o menos persistente. La carne es blanca y generalmente toma tintes rojizos o amarillos. Son setas en general comestibles excepto las del grupo Xanthoderma que son indigestas o algo tóxicas.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestibles:</strong> Agaricus campestris (Barrengorri, Champiñón de campa), A. bisporus (Champiñón cultivado), A. silvicola, A. macrosporus, A. arvensis (bola de nieve), A. augustus, etc.</p>
                    <p><strong>Tóxicos o indigestos:</strong> A. xanthoderma, A. meleagris, etc.</p>
                </div>
            </div>

            <!-- Amanita -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Amanita</h2>
                <p>Son setas carnosas, terrícolas, no hay ninguna lignícola, setas heterogéneas, separable el pie del sombrero, cutícula separable y algo viscosa generalmente, restos del velo general en forma de placas en el sombrero, pie central con <strong>volva</strong> en la base del pie y con <strong>anillo</strong> casi siempre presente menos en el subgénero Amanitopsis. Esporas blancas. En este género se encuentran las setas más tóxicas.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestibles apreciadas:</strong> Amanita caesarea, A. rubescens, A. ponderosa, etc.</p>
                    <p><strong>Tóxicas mortales:</strong> A. phalloides, A. verna, A. virosa.</p>
                    <p><strong>Muy tóxicas:</strong> A. pantherina, A. muscaria.</p>
                </div>
            </div>

            <!-- Boletus -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Boletus</h2>
                <p>El género <em>Boletus</em> y afines (<em>Xerocomus</em>) comprende setas carnosas en las que su himenio está formado por <strong>tubos</strong> en lugar de láminas, estos tubos terminan en poros más o menos redondeados por donde caen las esporas al madurar. El sombrero suele ser hemisférico, convexo y finalmente algo extendido. El pie de los Boletus es central, puede llevar anillo o no, algunos pies están provistos de retículo y otros de granulaciones. La carne es putrescible y en muchos casos al contacto con el aire toma una coloración azul más o menos intensa. Los Boletus son setas <strong>simbiontes</strong> formando micorrizas con árboles y arbustos.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestibles de gran calidad:</strong> B. edulis, B. aereus, B. reticulatus, B. pinophilus, B. appendiculatus, B. regius, B. badius, B. erythropus, etc.</p>
                    <p><strong>Indigestos o algo tóxicos:</strong> B. satanas, B. purpureus, B. lupinus, B. rhodopurpureus, B. rhodoxanthus, etc.</p>
                </div>
            </div>

            <!-- Cantharellus -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Cantharellus</h2>
                <p>Comprende pocas especies, ninguna tóxica y alguna buena comestible. Las setas de este género tienen forma de <strong>copa o trompeta</strong> y en lugar de láminas debajo del sombrero tienen pliegues más o menos marcados que en algunos casos parecen verdaderas láminas. Algunas setas son carnosas y otras algo coriáceas. Todas son de sabor y olor agradables, afrutado.</p>
                <div class="genero-ejemplos">
                    <p><strong>Especies más importantes:</strong> C. cibarius, C. lutescens, C. cornucopioides, C. cinereus, etc.</p>
                </div>
            </div>

            <!-- Clitocybe -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Clitocybe</h2>
                <p>Está formado por numerosas setas de difícil clasificación, suelen tener colores parecidos, blanquecinos o grisáceos la mayoría, existiendo pocas especies de colores vivos. El sombrero suele ser convexo al principio e <strong>infundibuliforme</strong> (forma de embudo) al final. Cutícula no separable en su mayoría y láminas decurrentes. La mayoría son terrícolas.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestibles:</strong> C. alexandrii, C. geotropa, C. nebularis, etc.</p>
                    <p><strong>Tóxicos:</strong> C. rivulosa, C. dealbata, C. cerussata.</p>
                </div>
            </div>

            <!-- Clitopilus -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Clitopilus</h2>
                <p>Está formado por unas pocas setas entre las cuales no hay ninguna tóxica y sí alguna buena comestible. Son homogéneas (no separable el sombrero del pie), sombrero irregular y láminas decurrentes. Esporada rosa y olor de harina normalmente.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestibles:</strong> C. prunulus (errotari, molinera) y C. truncatus (ahora en el género Rhodocybe).</p>
                </div>
            </div>

            <!-- Collybia -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Collybia</h2>
                <p>Está formado por bastantes especies de tamaño pequeño-mediano con alguna excepción, sombrero liso y pie cartilaginoso o elástico parecido a las del género <em>Marasmius</em>. Son terrícolas o lignícolas. No hay especies tóxicas siendo la mayoría sin valor culinario.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> C. dryophila, C. fusipes, C. asema, C. butyracea, C. maculata, etc.</p>
                </div>
            </div>

            <!-- Coprinus -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Coprinus</h2>
                <p>Está formado por numerosas especies de tamaño pequeño o mediano que pueden ser terrícolas, lignícolas o fimícolas. La mayoría de los Coprinus son <strong>delicuescentes</strong>, las láminas se ponen negras al madurar las esporas acabando por transformarse en un líquido negruzco. Las láminas suelen ser libres y el pie lleva un anillo que puede ser fugaz.</p>
                <div class="genero-ejemplos">
                    <p><strong>Buen comestible:</strong> C. comatus (urbeltz, barbuda).</p>
                    <p><strong>Tóxico (con alcohol):</strong> C. atramentarius.</p>
                    <p><strong>Más comunes:</strong> C. micaceus, C. desseminatus, C. niveus, etc.</p>
                </div>
            </div>

            <!-- Cortinarius -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Cortinarius</h2>
                <p>Está formado por numerosísimas especies muy difíciles de distinguir entre sí; es probablemente el género con más especies, más de 1000 según algunos micólogos. El carácter al cual debe su nombre es una <strong>cortina</strong> que presentan los ejemplares jóvenes, restos del velo general, que parece una tela de araña. Las esporas son de color ocre. Solo hay una especie comestible apreciada, por el contrario hay muchos tóxicos y varios mortales.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestible:</strong> C. praestans.</p>
                    <p><strong>Venenosos mortales:</strong> C. orellanus, C. phoeniceus.</p>
                    <p><strong>Venenosos:</strong> C. splendens, C. semisanguineus, C. sanguineus, etc.</p>
                </div>
            </div>

            <!-- Entoloma -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Entoloma</h2>
                <p>Está formado por especies homogéneas, de tamaño mediano-grande, carnosas generalmente, los bordes del sombrero enrollados de jóvenes y pie carnoso o en algunos casos frágil, láminas escotadas y la esporada es de color <strong>rosa</strong>. No hay ningún Entoloma que merezca la pena consumir y sí algunos tóxicos. En este género se encuentra el <em>E. lividum</em>, que produce el 90% de los envenenamientos en el País Vasco.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> E. lividum, E. vernum, E. rhodopolium, E. clypeatum, etc.</p>
                </div>
            </div>

            <!-- Hydnum -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Hydnum</h2>
                <p>Las pocas especies de este género son fácilmente identificables porque presentan el himenio con <strong>aguijones</strong> en lugar de láminas o tubos. Son setas terrícolas y la carne blanca más o menos dura.</p>
                <div class="genero-ejemplos">
                    <p><strong>Mejor comestible:</strong> H. Repandum (tripaki, lengua de vaca), muy conocida y recolectada en nuestra zona.</p>
                </div>
            </div>

            <!-- Hygrophorus e Hygrocybe -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Hygrophorus e Hygrocybe</h2>
                <p>Comprenden especies de tamaño mediano-grande cuya característica principal son las láminas de aspecto <strong>céreo</strong> y generalmente decurrentes. Son setas que pueden salir en otoño o invierno y en praderas o bosques. No hay ninguna tóxica aunque sí alguna sospechosa, y la mayoría son comestibles. Suelen tener vivos colores con algunas excepciones de colores blancos y grises.</p>
                <div class="genero-ejemplos">
                    <p><strong>Especies más importantes:</strong> H. marzuolus, H. pratensis, H. poetarum, H. eburneus, H. limacinus, H. nemoreus, etc.</p>
                </div>
            </div>

            <!-- Inocybe -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Inocybe</h2>
                <p>Está formado por más de 300 especies de difícil clasificación. Para clasificar sus especies correctamente hay que recurrir al microscopio. Son setas de pequeño-mediano tamaño, sombrero generalmente <strong>cónico</strong> y se resquebraja radialmente, superficie seca y fibrillosa. No hay ninguna comestible y sí muchas tóxicas. Alguna como <em>I. patoullardii</em> puede ser mortal.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> I. asterospora, I. patoullardii, I. geophylla, I. fastigiata, I. maculata, etc.</p>
                </div>
            </div>

            <!-- Lactarius -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Lactarius</h2>
                <p>Tiene alrededor de 150 especies y como su nombre indica son setas que al romperse segregan <strong>látex o leche</strong>. El sombrero suele tener colores apagados, salvo excepciones, y algunos suelen tener círculos concéntricos. Las láminas suelen ser desiguales, con lamélulas y su color blanquecino o crema. Son terrícolas y viven en bosques, en simbiosis con diferentes árboles.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestibles:</strong> L. deliciosus (esnegorri, niscalo), L. sanguifluus, L. semisanguifluus, L. quieticolor, L. vellereus, L. salmonicolor, etc.</p>
                    <p><strong>Tóxico:</strong> Lactarius torminosus (esnegorri faltsu).</p>
                </div>
            </div>

            <!-- Lepiota y afines -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Lepiota y afines</h2>
                <p>La característica principal es que tiene <strong>escamas</strong> en el sombrero, escamas persistentes que no desaparecen con la lluvia. Los sombreros suelen ser secos, las láminas libres y el pie con anillo que a veces se puede deslizar. Las esporas son blancas. Por precaución hay que desechar todas las Lepiotas de pequeño tamaño.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestibles:</strong> M. procera (galanperna), M. rhacodes, M. excoriata, M. gracilenta, M. mastoidea, etc.</p>
                    <p><strong>Mortales:</strong> L. brunneo-incarnata, L. helveola, L. castanea, L. josserandii, etc.</p>
                    <p><strong>Venenosas:</strong> L. acutesquamosa, L. cristata, L. felina, etc.</p>
                </div>
            </div>

            <!-- Lycoperdon -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Lycoperdon</h2>
                <p>El nombre significa "pedo de lobo" y es el nombre con que se conoce popularmente a la mayoría de sus especies. Sus carpóforos tienen forma de <strong>pera o de bombilla</strong> y tienen una envoltura exterior, lisa o decorada con aguijones o verrugas, que al madurar se abre por un orificio. No se conocen especies tóxicas y algunas son comestibles en estado joven.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> L. perlatum, L. molle, L. piriforme, L. umbrinum, etc.</p>
                </div>
            </div>

            <!-- Marasmius -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Marasmius</h2>
                <p>Está formado por numerosas setas de pequeño tamaño que viven relacionados con plantas herbáceas o sobre restos vegetales. Son setas <strong>imputrescibles</strong> que se pueden secar y luego al mojarse recuperan su aspecto normal. El sombrero es pequeño, láminas libres y pie central, largo, delgado y resistente a la torsión.</p>
                <div class="genero-ejemplos">
                    <p><strong>Excelente comestible:</strong> M. Oreades (sederuela, carrerilla).</p>
                    <p><strong>Más comunes:</strong> M. alliaceus, M. rotula, M. confluens, etc.</p>
                </div>
            </div>

            <!-- Melanoleuca -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Melanoleuca</h2>
                <p>El nombre significa "negro-blanco" y es el contraste entre el blanco de las láminas y el negro u oscuro del sombrero. Son setas de tamaño mediano-grande con sombrero <strong>mamelonado</strong>, carnoso en el centro y delgado en los bordes. No hay ninguna Melanoleuca tóxica siendo comestibles la mayoría.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> M. grammopodia, M. cognata, M. melaleuca, M. evenosa, etc.</p>
                </div>
            </div>

            <!-- Morchella -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Morchella</h2>
                <p>Pertenece a la clase Ascomycetes y es el género más importante desde el punto de vista gastronómico aunque todas sus especies son <strong>tóxicas en crudo</strong> debido a una hemolisina termolábil que se destruye a 60°C. Las Morchellas están provistas de un sombrero en forma de colmena con alvéolos. Salen en primavera.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> M. Vulgaris, M. Conica, M. Costata, M. Elata, M. Rotunda, etc.</p>
                </div>
            </div>

            <!-- Panaeolus -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Panaeolus</h2>
                <p>Es un género afín a Coprinus, tiene pocas especies y muchas son <strong>fimícolas</strong> (viven sobre estiércol). Son setas de pequeño-mediano tamaño, sombrero campanulado o hemisférico, pie delgado y esbelto. No hay especies comestibles y algunas son consideradas <strong>alucinógenas</strong>.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> P. sphinctrinus (seta de los locos), P. semiovatus, P. campanulatus, etc.</p>
                </div>
            </div>

            <!-- Peziza -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Peziza</h2>
                <p>Las especies de este género, que pertenece a la Clase Ascomycetes, tienen forma de <strong>copa</strong> sin pie o con un pie rudimentario muy corto. Son de tamaño pequeño-mediano. Suelen fructificar más especies en primavera y pueden salir en madera, tierra, estiércol e incluso en paredes.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> P. cerea, P. repanda, P. vesiculosa, P. badia, etc.</p>
                </div>
            </div>

            <!-- Russula -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Russula</h2>
                <p>Las especies están formadas por células redondeadas (esferocistos) y tienen la carne <strong>quebradiza</strong> similar a la tiza. Está formado por muchas especies (alrededor de 350) difíciles de identificar. Suelen ser de colores vivos. Las Russulas que no pican son comestibles. No hay Russulas tóxicas, todo lo más pueden causar algún trastorno gastrointestinal.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestibles importantes:</strong> R. virescens (guibelurdin), R. cyanoxhanta (urretxa), R. vesca, R. heterophylla, R. parazurea, etc.</p>
                </div>
            </div>

            <!-- Scleroderma -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Scleroderma</h2>
                <p>Es parecido al género Lycoperdon aunque la piel exterior es <strong>muy dura</strong> a diferencia de los Lycoperdones y suele estar decorada por escamas. Los carpóforos tienen forma de tubérculo con micelio en su base. No hay comestibles en este género.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> S. aurantium, S. verrucosum, S. areolatum, S. geaster, etc.</p>
                </div>
            </div>

            <!-- Stereum -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Stereum</h2>
                <p>Todas las especies son lisas en la parte inferior del sombrero, carecen de láminas o de poros y su aspecto es en forma de <strong>concha</strong> con bordes ondulados, careciendo de pie. Son coriáceas y lignícolas. No tienen ningún valor culinario por su dureza.</p>
                <div class="genero-ejemplos">
                    <p><strong>Más comunes:</strong> S. hirsutum, S. insignitum, S. sanguinolentum, S. rugosum, etc.</p>
                </div>
            </div>

            <!-- Tricholoma -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Tricholoma</h2>
                <p>Es uno de los géneros más importantes tanto por el número de especies como por el número de comestibles. Abarca especies de tamaño mediano-grande, carnosas, homogéneas, tienen pie central normalmente carnoso. Normalmente viven en bosques. No hay especies mortales y pocas tóxicas.</p>
                <div class="genero-ejemplos">
                    <p><strong>Comestibles:</strong> T. portentosum (capuchina), T. terreum (negrilla, ziza arre), T. scalpturatum, T. orirubens, T. columbetta (palomita), etc.</p>
                    <p><strong>Tóxicos:</strong> T. pardinum, T. sulphureum, T. josserandii, etc.</p>
                    <p><strong>Precaución (rabdomiolisis):</strong> T. equestre y T. auratum (zaldun-ziza) - no consumir en grandes cantidades.</p>
                </div>
            </div>

            <!-- Volvaria -->
            <div class="genero-item">
                <h2 class="genero-titulo">Género Volvaria</h2>
                <p>Consta de pocas especies (alrededor de 20) y debe su nombre a la <strong>volva</strong> que presentan en la base del pie todas sus especies. Se diferencian de las Amanitas en que no llevan anillo y las esporas y las láminas son rosadas. Pueden ser terrícolas, lignícolas y parásitas. No hay ninguna tóxica.</p>
                <div class="genero-ejemplos">
                    <p><strong>Especies cultivadas:</strong> V. bombycina y V. volvacea.</p>
                </div>
            </div>

