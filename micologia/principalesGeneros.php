            <h1 class="page-title">Géneros más importantes</h1>
            <p class="page-description">Vamos a destacar los rasgos más importantes de los géneros de setas más comunes de forma que cuando encontremos una seta, aunque nos resulte difícil saber exactamente cuál es, por lo menos tengamos una idea aproximada del género al que pertenece y con ese dato podamos localizarla en los libros especializados.</p>
